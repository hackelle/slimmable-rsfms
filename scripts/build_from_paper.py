# Build static/js/data.js from the paper's vector figures (matplotlib PDFs), so the site shows exactly the plotted numbers.
# Usage: python3 scripts/build_from_paper.py <overleaf>/figures/plots static/js/data.js
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_pdf import plot, legend
P, OUT = sys.argv[1], sys.argv[2]
r4 = lambda v: round(float(v), 4)
L = lambda n: {i['color']: i['label'] for i in legend(f'{P}/legends/{n}_legend_only.pdf')}
Ld = lambda n: {i['dash']: i['label'] for i in legend(f'{P}/legends/{n}_legend_only.pdf')}

def clean(pts):
    pts = sorted([[r4(min(max(x, 0), 1)), r4(y)] for x, y in pts])
    return pts
def series(pdf, cmap, dmap=None, fmt=None):
    d = plot(pdf)
    out = []
    for s in d['series']:
        lab = cmap.get(s['color'], s['color'])
        ver = dmap.get(s['dash'], s['dash']) if dmap else None
        out.append(dict(label=fmt(lab, ver) if fmt else lab, model=lab, version=ver, color=s['color'], pts=clean(s['pts'])))
    bands = [dict(color=b['color'], pts=[[r4(min(max(x, 0), 1)), r4(y)] for x, y in b['pts']]) for b in d['bands']]
    refs = [dict(label=cmap.get(r['color'], ''), y=r4(r['pts'][0][1])) for r in d['refs']]
    return out, bands, refs

DS = {'m-eurosat': ('Accuracy', 'Scene classification, single-label, 10 classes'),
      'm-bigearthnet': ('mAP', 'Scene classification, multi-label, 43 classes'),
      'm-brick-kiln': ('Accuracy', 'Scene classification, binary'),
      'm-so2sat': ('Accuracy', 'Scene classification, 17 local climate zones'),
      'm-cashew-plant': ('IoU', 'Semantic segmentation, 7 classes'),
      'm-SA-crop-type': ('IoU', 'Semantic segmentation, 10 crop types'),
      'oscd': ('F1 (macro)', 'Change detection, binary')}
data = {'posthoc': {}, 'native': {}}
cm = L('post_hoc_slimming_existing_fms')
for ds, (yl, desc) in DS.items():
    s, _, _ = series(f'{P}/post_hoc/post_hoc_slimming_existing_fms_average_by_model_{ds}_nolegend.pdf', cm)
    data['posthoc'][ds] = dict(ylabel=yl, desc=desc, series=[dict(label=x['label'], pts=x['pts']) for x in s])
cm = L('native_vs_posthoc')
for ds in ['m-eurosat', 'm-bigearthnet', 'm-brick-kiln', 'm-so2sat']:
    s, _, _ = series(f'{P}/training_slimableOrNot/native_vs_posthoc_{ds}_nolegend.pdf', cm)
    data['native'][ds] = dict(ylabel=DS[ds][0], series=[dict(label=x['label'], pts=x['pts']) for x in s])
cm = L('CV_vs_RS_retention')
for key, f, yl in [('fig1a', 'CV_vs_RS_retention', 'Rel. retention rate'), ('fig1b', 'CV_vs_RS_m-eurosat', 'Accuracy on m-eurosat')]:
    s, b, r = series(f'{P}/post_hoc/{f}_nolegend.pdf', cm)
    data[key] = dict(ylabel=yl, series=[dict(label=x['label'], color=x['color'], pts=x['pts']) for x in s], bands=b, refs=r)

rob = {'finetune': {}, 'classwise': {}, 'imbalance': {}}
cm = L('knn_vs_linear')
for m, lab in [('dofa_large', 'DOFA (large)'), ('terramind_large', 'TerraMind-1.0 (large)'), ('prithvi2_600', 'Prithvi-EO-2.0 (600M)')]:
    rob['finetune'][lab] = {}
    for ds in ['m-eurosat', 'm-bigearthnet']:
        s, _, _ = series(f'{P}/knn_vs_linear/knn_vs_linear_{m}_{ds}_nolegend.pdf', cm)
        rob['finetune'][lab][ds] = [dict(label=x['label'], pts=x['pts']) for x in s]
mods = L('post_hoc_slimming_existing_fms_failure_modes_models')
ver = Ld('post_hoc_slimming_existing_fms_failure_modes_versions')
for lab in ['DOFA (base)', 'TerraMind-1.0 (base)', 'Prithvi-EO-2.0 (300M)']:
    s, _, _ = series(f'{P}/failure_mode_classes/m-bigearthnet_{lab}_AP_of_globally_best_class_nolegend.pdf', mods, ver)
    rob['classwise'][lab] = [dict(label=x['version'], pts=x['pts']) for x in s]
mods = L('post_hoc_slimming_existing_fms_failure_mode_correlation_models')
ver = Ld('post_hoc_slimming_existing_fms_failure_mode_correlation_versions')
s, _, _ = series(f'{P}/failure_mode_correlation/m-so2sat_AP_of_globally_best_class_nolegend.pdf', mods, ver)
rob['geo'] = [dict(model=x['model'], version=x['version'], pts=x['pts']) for x in s]
mods = L('post_hoc_slimming_existing_fms_failure_mode_imbalance_models')
ver = Ld('post_hoc_slimming_existing_fms_failure_mode_imbalance_versions')
for lab, fn in [('DOFA (base)', 'DOFA (base)'), ('TerraMind-1.0 (base)', 'TerraMind-1.0 (base)'), ('Prithvi-EO-2.0 (300M)', 'Prithvi-EO-2.0 (300M)')]:
    s, _, _ = series(f'{P}/failure_mode_imbalance/m-eurosat_{fn}_nolegend.pdf', mods, ver)
    rob['imbalance'][lab] = [dict(label=x['version'], pts=x['pts']) for x in s]

open(OUT, 'w').write('/* Generated by scripts/build_from_paper.py: every curve is read from the vector paths of the paper figures.\n'
                     '   x is relative compute (FLOPs / full-width FLOPs). */\n'
                     'window.PAPER_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n'
                     'window.ROBUST_DATA = ' + json.dumps(rob, separators=(',', ':')) + ';\n')
# summary for checking
for ds, v in data['posthoc'].items():
    print(ds, [(x['label'][:14], round(x['pts'][0][0] * 100, 2), round(x['pts'][0][1] / x['pts'][-1][1] * 100, 1)) for x in v['series']])
print('fig1a', [(x['label'], x['pts'][0]) for x in data['fig1a']['series']])
print('fig1b', [(x['label'], x['pts'][0], x['pts'][-1]) for x in data['fig1b']['series']], data['fig1b']['refs'])
print('ft', {k: {d: [x['label'] for x in v] for d, v in vv.items()} for k, vv in rob['finetune'].items()})
print('cls', {k: [(x['label'], x['pts'][0][1], x['pts'][-1][1]) for x in v] for k, v in rob['classwise'].items()})
print('geo', [(x['model'], x['version'], x['pts'][0][1], x['pts'][-1][1]) for x in rob['geo']])
print('imb', {k: [(x['label'], x['pts'][0][1], x['pts'][-1][1]) for x in v] for k, v in rob['imbalance'].items()})
